function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  const toggle = document.getElementById("langToggle");
  if (toggle) toggle.textContent = lang === "ar" ? "English" : "العربية";
  // keep the invoice document itself LTR so numbers/QR layout stays stable in print
  const paper = document.getElementById("invoicePaper");
  if (paper) paper.dir = "ltr";
  try { localStorage.setItem("fawtara.lang", lang); } catch (e) {}
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

function currentLang() {
  try { return localStorage.getItem("fawtara.lang") || "en"; } catch (e) { return "en"; }
}
